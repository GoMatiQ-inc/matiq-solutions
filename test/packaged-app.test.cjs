const test = require("node:test"), assert = require("node:assert/strict");
const fs = require("node:fs/promises"), os = require("node:os"), path = require("node:path"), crypto = require("node:crypto");
const asar = require("@electron/asar"), sdk = require("@matiq-solutions/sdk");
const { packApp } = require("@matiq-solutions/sdk/package-app.cjs");
test("suite package preserves packaged native bytes, extra resources and executable mode", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "matiq-native-package-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const source=path.join(root,"app"), resources=path.join(root,"resources");
  await fs.mkdir(path.join(source,"src"),{recursive:true});await fs.mkdir(resources);
  const manifest={schema:1,id:"com.matiq.example",name:"Example",version:"1.0.0",sdk:1,dataVersion:1,runtime:"electron-45.2.3",targets:["darwin-arm64"],capabilities:[],adapter:"src/tool.cjs",workspace:"src/index.html",preload:"src/preload.cjs"};
  await fs.writeFile(path.join(source,"matiq-tool.json"),JSON.stringify(manifest));
  await fs.writeFile(path.join(source,"package.json"),JSON.stringify({version:"1.0.0"}));
  for(const file of ["tool.cjs","index.html","preload.cjs"])await fs.writeFile(path.join(source,"src",file),"entry");
  const native=Buffer.from([0,255,42,0,13,10]);
  await fs.writeFile(path.join(source,"src/addon.node"),native);
  await asar.createPackageWithOptions(source,path.join(resources,"app.asar"),{unpack:"**/*.node"});
  await fs.mkdir(path.join(resources,"engine"));await fs.writeFile(path.join(resources,"engine/helper"),native,{mode:0o755});
  const key=crypto.generateKeyPairSync("ed25519"), output=path.join(root,"tool.mqt");
  const options={resources,manifest,target:"darwin-arm64",extra:["engine"],output,privateKey:key.privateKey,publisher:"fixture",url:"https://example.com/releases/v1/tool.mqt"};
  const release=await packApp(options);
  const verified=sdk.inspect(await fs.readFile(output),{fixture:key.publicKey},"darwin-arm64");
  assert.deepEqual(verified.entries.find(e=>e.entryName==="src/addon.node").getData(),native);
  assert.deepEqual(verified.entries.find(e=>e.entryName==="engine/helper").getData(),native);
  if(process.platform!=="win32")assert.equal(verified.files["engine/helper"].executable,true);
  assert.equal(sdk.verify(release.signed,release.signature,key.publicKey),true);
  assert.equal(release.signed.packages["darwin-arm64"].sha256,verified.sha256);
  const fresh={...options,output:path.join(root,"fresh.mqt")};
  const retained=await fs.readFile(output);await assert.rejects(packApp(options),/already exists/);assert.deepEqual(await fs.readFile(output),retained);
  await assert.rejects(packApp({...fresh,manifest:{...manifest,id:"com.matiq.wrong"}}),/manifest differs/);
  await assert.rejects(packApp({...fresh,target:"win32-x64"}),/target declared/);
  await assert.rejects(packApp({...fresh,manifest:{...manifest,version:"2.0.0"}}),/version differs/);
  await assert.rejects(packApp({...fresh,extra:["src"]}),/overwrite/);
});
